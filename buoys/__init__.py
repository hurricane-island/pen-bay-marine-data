@buoys.command(name=ClickOptions.NAMES)
def buoys_names():
    """
    List available stations from static data.
    """
    files = sorted(DATA_DIR.glob("*.dat"))
    seen = set()
    for f in files:
        station = f.stem.split("_")[0].lower()
        if station not in seen:
            seen.add(station)
    for each in sorted(seen):
        print(each)



@file_group.command(name=ClickOptions.DESCRIBE)
@station_name
@data_table
def buoys_file_describe(name: StationName, table: TableName):
    """
    Summarize available observations for a station.
    """
    files = filter_buoy_flat_files(name, table)
    df = read_campbell_logger_files(list(files))
    summary = df.describe().T.drop(columns=["25%", "75%", "std"])
    # Add Median Absolute Deviation
    mad = df.select_dtypes(include="number").apply(
        lambda x: median_abs_deviation(x, nan_policy="omit")
    )
    summary["MAD"] = mad
    print("\nSamples:\n")
    print(summary)


def format_column_name_with_units(col: str) -> str:
    """
    Format a column name with its units if available.
    """
    if isinstance(col, tuple) and len(col) == 3:
        name, unit, _ = col
        return f"{name} ({unit})"
    return str(col)

def format_column_standard_name(col: str) -> str:
    """
    Replace with standard name if available, otherwise return the original column name.
    """
    try:
        vendor_name = VendoredNames(col[0])
        std_name = StandardNames[vendor_name.name]
        return std_name
    except (KeyError, ValueError):
        return col[0]

@file_group.command(name=ClickOptions.EXPORT)
@station_name
@qartod_configs_option
@qartod_test_option
@click.option(
    "--flag",
    type=click.Choice([3, 4]),
    default=3,
    help="Filter out this QARTOD flag. 3 = suspect/failed, 4 = failed. Defaults to 3.",
)
def buoys_file_export(
    name: StationName,
    qartod: tuple[str],
    test: TestTypes,
    flag: int
):
    """
    Export buoy data to a CSV with single header row.
    """
    sonde, _ = load_and_subset_multifile_table(name, TableName.SONDE, None, None)
    diagnostic, _ = load_and_subset_multifile_table(name, TableName.DIAGNOSTIC, None, None)
    df = sonde.drop(columns=["RECORD"]).join(diagnostic, how="left")[[
        VendoredNames.LATITUDE,
        VendoredNames.LONGITUDE,
        VendoredNames.SEA_WATER_TEMPERATURE,
        VendoredNames.SEA_WATER_SALINITY,
        VendoredNames.SEA_WATER_CHLOROPHYLL_RFU,
        VendoredNames.SEA_WATER_PHYCOERYTHRIN_RFU,
        VendoredNames.DISSOLVED_OXYGEN_SATURATION,
        VendoredNames.DISSOLVED_OXYGEN,
        VendoredNames.BAROMETRIC_PRESSURE
    ]]
    df.index.rename("time", inplace=True)
    unit_names = list(map(format_column_name_with_units, df.columns))
    std_names = list(map(format_column_standard_name, df.columns))
    df.columns = std_names  # use standard names for quality checks
    config_key_value = load_and_merge_qa_configs(qartod)
    qa = run_qartod_tests(df, config_key_value)
    for group in qa.groups.keys():
        flags = qa.get_group(group)[test]
        df[group] = df[group].where((flags < flag) | (flags == 9))
    df.columns = unit_names  # revert to original headers for export
    start = df.index.min()
    end = df.index.max()
    filepath = (
        EXPORT_DIR
        / name
        / (
            f"{start:%Y-%m-%d}_"
            f"{end:%Y-%m-%d}_"
            f"{'-'.join(Path(each).stem for each in qartod)}"
            f"-{test}"
        )
    ).with_suffix(".csv")
    filepath.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(filepath, header=unit_names)
    click.echo(f"Saved CSV file to {filepath}")


@plot.command(name=ClickOptions.TAIL)
@source_options
@plot_options
@qartod_configs_option
@qartod_test_option
@click.option(
    "--days",
    default=30,
    type=click.IntRange(min=0),
    help="Number of days to plot backwards from the end date. Defaults to 30 days.",
)
@click.option(
    "--end",
    default=datetime.now(),
    type=click.DateTime(formats=["%Y-%m-%d"]),
    help="End date for the analysis and plotting. Defaults to the current date and time.",
)
@click.option(
    "--scale/--no-scale",
    is_flag=True,
    default=False,
    help="Scale the output plot to remaining data, otherwise use the full range. Defaults to True.",
)
@figure_size((7.5, 3.0))
def buoys_plot_tail(
    name: StationName,
    table: TableName,
    series: StandardNames,
    qartod: tuple[str],
    days: int,
    test: TestTypes,
    end: datetime,
    image_format: ImageFormat,
    scale: bool,
    figsize: tuple[float, float]
):
    """
    Plot the most recent data from a buoy for a single data stream.
    """
    simplefilter(action="ignore", category=PerformanceWarning)
    if len(qartod) == 0:
        raise click.ClickException(
            "At least one QARTOD config file must be provided using the -q option."
        )
    start: datetime = end - timedelta(days=days)
    df, dropped = load_and_subset_multifile_table(name, table, start, end)
    if df.empty:
        raise click.ClickException(
            f"No local data for {name} {table} between {start} and {end}."
        )
    gps, _ = load_and_subset_multifile_table(name, TableName.DIAGNOSTIC, start, end)
    df = df.drop(columns=["RECORD"]).join(gps, how="left")
    renamed = list(map(format_column_standard_name, df.columns))
    units = {each: col[1] for each, col in zip(renamed, df.columns)}
    df.columns = renamed
    df = df[["Latitude", "Longitude", series]]
    config_key_value = load_and_merge_qa_configs(qartod)

    # Begin plotting
    fig, ax = plt.subplots(figsize=figsize)
    ax.plot(
        df.index,
        df[series],
        color="grey",
        linestyle="dashed",
        linewidth=1,
        zorder=2,
        label="raw",
    )
    ylim = (None, None)
    if series in config_key_value["streams"]:
        qa = run_qartod_tests(df, {
            "streams": {
                series: config_key_value["streams"][series]
            }
        }).get_group(series)
        gaps = cast(DataFrame, df.loc[qa["gap"] == 3, series])
        qa = qa[test]
        suspect = cast(DataFrame, df.loc[qa == 3, series])
        failed = cast(DataFrame, df.loc[qa == 4, series])
        remaining = df.loc[((qa < 3) | (qa == 9)), series].asfreq("h")

        ax.vlines(
            gaps.index,
            ymin=0,
            ymax=1,
            color="pink",
            linewidth=1,
            label="gap",
            transform=ax.get_xaxis_transform(),
            zorder=0
        )
        ax.vlines(
            get_climatology_breakpoints(config_key_value, series),
            ymin=0,
            ymax=1,
            color="black",
            linewidth=1,
            linestyle="dotted",
            label="climatology change",
            transform=ax.get_xaxis_transform(),
            zorder=0
        )
        ax.scatter(
            suspect.index,
            suspect,
            label="suspect",
            color="orange",
            marker="x",
            zorder=1,
        )
        ax.scatter(
            failed.index, failed, label="failed", color="red", marker="x", zorder=1
        )
        ax.plot(
            remaining.index,
            remaining,
            color="black",
            linestyle="solid",
            linewidth=1,
            zorder=2,
            label="filtered",
        )
        if scale:
            ylim = (remaining.min(), remaining.max())

    ax.vlines(
        dropped,
        ymin=0,
        ymax=1,
        color="cyan",
        linewidth=1,
        label="duplicate",
        transform=ax.get_xaxis_transform(),
        zorder=0
    )
    _start = df.index.min()
    _end = df.index.max()
    _days = (_end - _start).days
    display_name = series.replace("_", " ").title()
    if _start.year == _end.year:
        year_range = f"{_start.year}"
    else:
        year_range = f"{_start.year}-{_end.year}"
    ax.set_title(f"{name} {display_name} {year_range} ({test.replace('_', ' ')})".title())
    ax.set_xlabel("Date")
    ax.xaxis.set_tick_params(rotation=45)
    ax.set_xlim(_start, _end)
    ax.set_ylim(*ylim)
    ax.xaxis.set_major_locator(mdates.DayLocator(interval=(_days // 8) + 2))
    ax.xaxis.set_minor_locator(mdates.DayLocator(interval=1))
    ax.xaxis.set_major_formatter(mdates.DateFormatter("%b %d"))  # Customize format
    if units is not None:
        ax.set_ylabel(f"{units[series]}")
    ax.legend(bbox_to_anchor=(1, 1), loc='upper left')
    fig.tight_layout()
    filepath = (
        FIGURES_DIR
        / ClickOptions.TAIL
        / name
        / table
        / series
        / (
            f"{_start:%Y-%m-%d}_"
            f"{_end:%Y-%m-%d}_"
            f"{'-'.join(Path(each).stem for each in qartod)}"
            f"-{test}"
        )
    ).with_suffix(f".{image_format}")
    filepath.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(filepath, dpi=300, bbox_inches="tight")
    click.echo(f"Saved plot to {filepath}")
    plt.close(fig)  # clean up when testing to avoid memory issues with pytest and matplotlib


@plot.command(name=ClickOptions.DATASTREAM)
@source_options
@click.option(
    "--aggregate",
    default=Frequency.DAILY,
    type=click.Choice(Frequency, case_sensitive=False),
    required=True,
    help="Frequency for aggregation.",
)
@click.option(
    "--start",
    default=None,
    type=click.DateTime(formats=["%Y-%m-%d"]),
    help="Start date for filtering data.",
)
@click.option(
    "--end",
    default=None,
    type=click.DateTime(formats=["%Y-%m-%d"]),
    help="End date for filtering data.",
)
@click.option(
    "--size",
    nargs=2,
    default=(7.5, 4),
    type=(float, float),
    help="Figure size in inches (width, height).",
)
@plot_options
def buoys_plot_datastream(
    name: StationName,
    table: TableName,
    series: StandardNames,
    start=None,
    end=None,
    aggregate=Frequency.DAILY,
    size=(7.5, 4),
    **kwargs,
):
    """
    Plot a generic `DataStream` aggregated by either daily, weekly, or monthly. This
    will read in and concatenate all available data files for the station and table,
    then extract a deduplicated series for the data stream. The output
    is an image file formatted for a report or presentation.
    """
    files = filter_buoy_flat_files(name, table)
    df = read_campbell_logger_files(list(files))
    vendor_name = VendoredNames[series.name]
    local = DataFrame(df[vendor_name])
    units = local.columns[0][0]
    mask = ~df.index.duplicated(keep=False)
    if start is not None:
        mask &= df.index >= start
    if end is not None:
        mask &= df.index <= end
    unique = local[mask].sort_index()
    unique.index.rename("time", inplace=True)
    boxplot(
        unique,
        name,
        series,
        FIGURES_DIR / "datastream",
        units=units,
        freq=aggregate,
        figsize=size,
        **kwargs,
    )


@file_group.command(name="derivatives")
@station_name
@data_table
@click.argument(
    "series",
    type=click.Choice(StandardNames, case_sensitive=False),
)
@click.option(
    "--percentile",
    "-p",
    default=(0.90, 0.95, 0.99),
    multiple=True,
    type=float,
    help="Percentiles to calculate for the summary statistics. Accepts multiple values, e.g., -p 0.90 -p 0.95 -p 0.99",
)
def buoys_file_first_and_second_derivative(
    name: StationName,
    table: TableName,
    series: StandardNames,
    percentile: tuple[float, float, float]
):
    """
    Calculate the first and second derivative of a time series to identify
    rapid changes and spikes in the series. Performs hourly resampling to
    fill gaps, so that time differences are consistent. The output values
    are in units per second and per hour, respectively, to use as inputs 
    for a QARTOD configuration file.
    """
    files = filter_buoy_flat_files(name, table)
    df = read_campbell_logger_files(list(files))
    vendor_name = VendoredNames[series.name]
    ds = df[vendor_name]
    ds = ds.sort_index()
    ds = ds[~ds.index.duplicated(keep="first")].asfreq("h")  # resample filling gaps with NaN
    slope = ds.diff()
    summary = DataFrame(
        data={
            "|dy/dt| (/s)": (slope.abs() / 3600.0).squeeze(),
            "|d²y/dt²| (/hr)": slope.diff().abs().squeeze()
        },
        index=ds.index
    ).describe(percentiles=sorted(percentile)).map('{:.8f}'.format)
    click.echo(summary)
